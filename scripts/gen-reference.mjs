#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_OUT = path.join(ROOT, "site", "reference");
export const REFERENCE_FILES = ["cli.md", "mcp-tools.md", "schema.md"];
const HEADER = "<!-- generated by scripts/gen-reference.mjs; do not edit -->";

async function loadSources() {
  const dist = (...parts) => import(pathToFileURL(path.join(ROOT, "packages", ...parts)).href);
  const [{ buildProgram }, { toolDefinitions }, core] = await Promise.all([
    dist("basics", "dist", "program.js"),
    dist("basics", "dist", "mcp", "tools.js"),
    dist("core", "dist", "index.js"),
  ]);
  return { program: buildProgram(), tools: toolDefinitions(), core };
}

function cell(value) {
  return String(value ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ")
    .trim();
}

function formatType(prop) {
  if (!prop || typeof prop !== "object") return "unknown";
  if (prop.const !== undefined) return `\`${JSON.stringify(prop.const)}\``;
  if (Array.isArray(prop.enum)) return prop.enum.map((value) => `\`${value}\``).join(" \\| ");
  if (Array.isArray(prop.anyOf)) return prop.anyOf.map(formatType).join(" \\| ");
  const type = Array.isArray(prop.type) ? prop.type[0] : prop.type;
  if (type === "array") return `${formatType(prop.items ?? { type: "string" })}[]`;
  if (type === "object") {
    if (prop.properties) return `{ ${Object.keys(prop.properties).join(", ")} }`;
    const extra = prop.additionalProperties;
    if (extra && typeof extra === "object") return `map<string, ${formatType(extra)}>`;
    return "object";
  }
  return type ? `\`${type}\`` : "unknown";
}

function formatDefault(value) {
  if (value === undefined) return "—";
  return `\`${typeof value === "string" ? value : JSON.stringify(value)}\``;
}

function renderCommand(command, chain, depth) {
  const names = [...chain, command.name()];
  const lines = [`${"#".repeat(depth + 2)} \`${names.join(" ")}\``, ""];
  if (command.description()) lines.push(command.description(), "");

  lines.push("```", `${names.join(" ")} ${command.usage()}`.trim(), "```", "");

  if (!command.options.length) {
    lines.push("No options.", "");
  } else {
    lines.push("| Flag | Description | Default |", "| --- | --- | --- |");
    for (const option of command.options) {
      const description = `${option.description ?? ""}${option.mandatory ? " (required)" : ""}`;
      lines.push(`| \`${option.flags}\` | ${cell(description)} | ${formatDefault(option.defaultValue)} |`);
    }
    lines.push("");
  }

  for (const child of command.commands) lines.push(...renderCommand(child, names, depth + 1));
  return lines;
}

function renderCli(program) {
  return [HEADER, "", "# CLI reference", "", "Generated from the `basics` command tree.", "", ...renderCommand(program, [], 0)];
}

function exampleValue(name, prop) {
  if (prop.const !== undefined) return prop.const;
  if (Array.isArray(prop.enum)) return prop.enum[0];
  if (Array.isArray(prop.anyOf)) return exampleValue(name, prop.anyOf[0]);
  const type = Array.isArray(prop.type) ? prop.type[0] : prop.type;
  if (type === "string") {
    if (/path|dir/i.test(name)) return "./project";
    if (name === "id" || name === "project") return "fastapi";
    if (name === "agent") return "claude-code";
    if (name === "query") return "rest api";
    return "example";
  }
  if (type === "integer" || type === "number") return 1;
  if (type === "boolean") return true;
  if (type === "array") return [exampleValue(name, prop.items ?? { type: "string" })];
  if (type === "object") return {};
  return null;
}

function renderTools(tools) {
  const lines = [
    HEADER,
    "",
    "# MCP tools",
    "",
    "Tools registered by the Basics MCP server. Call them over stdio (`basics-mcp`) or HTTP (`basics ui`).",
    "",
  ];
  for (const tool of tools) {
    lines.push(`## \`${tool.name}\``, "", tool.description, "");
    const properties = tool.inputSchema.properties ?? {};
    const required = new Set(tool.inputSchema.required ?? []);
    const names = Object.keys(properties);
    if (!names.length) {
      lines.push("No inputs.", "");
    } else {
      lines.push("| Input | Type | Required | Description |", "| --- | --- | --- | --- |");
      for (const name of names) {
        const prop = properties[name];
        lines.push(`| \`${name}\` | ${formatType(prop)} | ${required.has(name) ? "yes" : "no"} | ${cell(prop.description ?? "—")} |`);
      }
      lines.push("");
    }
    const args = {};
    for (const name of names) if (required.has(name)) args[name] = exampleValue(name, properties[name]);
    lines.push("Minimal call:", "", "```json", JSON.stringify({ name: tool.name, arguments: args }, null, 2), "```", "");
  }
  return lines;
}

function commonFieldNames(schemas) {
  const [first, ...rest] = Object.values(schemas);
  const keys = Object.keys(first.properties ?? {});
  return keys.filter((key) => key !== "type" && rest.every((schema) => key in (schema.properties ?? {})));
}

function fieldRow(name, prop, required) {
  const isRequired = required.includes(name) && prop.default === undefined;
  const description = prop.description ?? (name === "type" ? "Note type." : "—");
  return `| \`${name}\` | ${formatType(prop)} | ${isRequired ? "yes" : "no"} | ${formatDefault(prop.default)} | ${cell(description)} |`;
}

function renderSchema(core) {
  const schemas = core.noteJsonSchemas();
  const types = core.NOTE_TYPES;
  const common = commonFieldNames(schemas);
  const lines = [
    HEADER,
    "",
    "# Vault schema reference",
    "",
    "Notes are Markdown files with YAML frontmatter. Unknown fields are preserved on read and write.",
    "",
    "## Common fields",
    "",
    "| Field | Type | Required | Default | Description |",
    "| --- | --- | --- | --- | --- |",
  ];

  const first = schemas[types[0]];
  for (const name of common) lines.push(fieldRow(name, first.properties[name], first.required ?? []));
  lines.push("");

  for (const type of types) {
    const schema = schemas[type];
    lines.push(`## \`${type}\` notes`, "", `Stored in \`${core.TYPE_DIRS[type]}/\`.`, "");
    lines.push("| Field | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |");
    for (const [name, prop] of Object.entries(schema.properties)) {
      lines.push(fieldRow(name, prop, schema.required ?? []));
    }
    lines.push("");
  }

  lines.push(
    "## `basics.json`",
    "",
    "Written by `basics export` in a project root and read by `basics check`.",
    "",
    "```json",
    JSON.stringify(
      { stack: ["fastapi", "react"], targets: ["agents", "claude"], project: "my-app", versions: { fastapi: "0.115" } },
      null,
      2,
    ),
    "```",
    "",
    "| Field | Type | Required | Default | Description |",
    "| --- | --- | --- | --- | --- |",
    "| `stack` | `string`[] | yes | — | Tech ids exported for the project. |",
    "| `targets` | `agents` \\| `claude` \\| `cursor`[] | yes | — | Agent files to write. |",
    "| `project` | `string` | no | — | Id of the project note linked to this directory. |",
    "| `versions` | map<string, `string`> | no | — | Version override per tech id. |",
    "",
    "## `pack.json`",
    "",
    "Manifest of a note pack, shipped in `packs/<name>/pack.json`.",
    "",
    "```json",
    JSON.stringify(
      {
        name: "python-api",
        version: "1.0.0",
        description: { en: "Python API stack notes", es: "Notas de stack para APIs en Python" },
        requires: ["core-layers"],
        languages: ["en", "es"],
      },
      null,
      2,
    ),
    "```",
    "",
    "| Field | Type | Required | Default | Description |",
    "| --- | --- | --- | --- | --- |",
    "| `name` | `string` | yes | — | Pack id, lowercase letters, digits and dashes. |",
    "| `version` | `string` | yes | — | Dot-separated version compared numerically. |",
    "| `description` | map<string, `string`> | yes | — | Short description per language. |",
    "| `requires` | `string`[] | no | `[]` | Packs installed before this one. |",
    "| `languages` | `string`[] | yes | — | Languages the pack has notes for (at least one). |",
    "",
    "## `basics.vault.json`",
    "",
    "Committed at the vault root. `basics init` writes it; old vaults without it keep working.",
    "",
    "```json",
    JSON.stringify({ schemaVersion: core.CURRENT_SCHEMA_VERSION }, null, 2),
    "```",
    "",
    "| Field | Type | Required | Default | Description |",
    "| --- | --- | --- | --- | --- |",
    `| \`schemaVersion\` | \`integer\` | yes | \`${core.CURRENT_SCHEMA_VERSION}\` | Vault schema version written by this build. A newer value means the vault needs a newer basics. |`,
    "",
  );

  return lines;
}

export async function generate(outDir = DEFAULT_OUT) {
  const { program, tools, core } = await loadSources();
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "cli.md"), `${renderCli(program).join("\n")}\n`);
  fs.writeFileSync(path.join(outDir, "mcp-tools.md"), `${renderTools(tools).join("\n")}\n`);
  fs.writeFileSync(path.join(outDir, "schema.md"), `${renderSchema(core).join("\n")}\n`);
}

const isMain = process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  const { values } = parseArgs({ options: { out: { type: "string" } } });
  const outDir = values.out ? path.resolve(values.out) : DEFAULT_OUT;
  await generate(outDir);
  console.log(`wrote reference docs to ${path.relative(ROOT, outDir) || outDir}`);
}
