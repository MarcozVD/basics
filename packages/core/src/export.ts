import { renderContext, stackContext } from "./query.js";
import type { Vault } from "./vault.js";

export type ExportTarget = "agents" | "claude" | "cursor";

export interface ExportFile {
  /** Path relative to the project dir, forward slashes. */
  path: string;
  /** Full desired contents of the file. */
  content: string;
}

const STACK_BANNER = "<!-- generated by basics; edit the vault, not this file -->";
const BLOCK_START = "<!-- basics:start -->";
const BLOCK_END = "<!-- basics:end -->";
const CURSOR_PATH = ".cursor/rules/stack.mdc";

/** Upsert a marked block into an agent file, keeping everything outside the block untouched. */
export function upsertBlock(existing: string | null, block: string): string {
  if (existing === null) return `# Agent instructions\n\n${block}\n`;
  const start = existing.indexOf(BLOCK_START);
  const end = start >= 0 ? existing.indexOf(BLOCK_END, start + BLOCK_START.length) : -1;
  if (start >= 0 && end >= 0) {
    return `${existing.slice(0, start)}${block}${existing.slice(end + BLOCK_END.length)}`;
  }
  if (!existing) return `${block}\n`;
  const separator = existing.endsWith("\n\n") ? "" : existing.endsWith("\n") ? "\n" : "\n\n";
  return `${existing}${separator}${block}\n`;
}

/** Stack ids grouped by layer, in the order they first appear. */
function byLayer(vault: Vault, techIds: string[]): [string, string[]][] {
  const layers = new Map<string, string[]>();
  for (const id of techIds) {
    const note = vault.get(id);
    if (note?.data.type !== "tech") continue;
    for (const layer of [note.data.layer].flat()) {
      const ids = layers.get(layer) ?? [];
      if (!ids.includes(id)) ids.push(id);
      layers.set(layer, ids);
    }
  }
  return [...layers.entries()];
}

function agentBlock(vault: Vault, techIds: string[]): string {
  return [
    BLOCK_START,
    "## Stack",
    "",
    ...byLayer(vault, techIds).map(([layer, ids]) => `${layer}: ${ids.join(", ")}`),
    "",
    "Follow the practices in STACK.md and run its checks before finishing a task.",
    "",
    "If the basics MCP server is available, use get_stack_context / propose_note to read or extend the stack knowledge.",
    BLOCK_END,
  ].join("\n");
}

/** Files a project needs so its coding agents can follow the stack. */
export function renderExport(
  vault: Vault,
  techIds: string[],
  targets: ExportTarget[],
  existing: (relPath: string) => string | null,
): ExportFile[] {
  const ctx = stackContext(vault, techIds);
  if (ctx.missing.length) throw new Error(`unknown tech ids: ${ctx.missing.join(", ")}`);

  const ids = [...new Set(techIds)];
  const context = renderContext(vault, ids);
  const files: ExportFile[] = [{ path: "STACK.md", content: `${STACK_BANNER}\n\n${context}\n` }];
  const block = agentBlock(vault, ids);

  for (const target of new Set(targets)) {
    if (target === "agents" || target === "claude") {
      const file = target === "agents" ? "AGENTS.md" : "CLAUDE.md";
      files.push({ path: file, content: upsertBlock(existing(file), block) });
    } else {
      files.push({
        path: CURSOR_PATH,
        content: `---\ndescription: Project stack (generated by basics)\nalwaysApply: true\n---\n\n${context}\n`,
      });
    }
  }

  return files;
}
