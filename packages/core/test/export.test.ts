import assert from "node:assert/strict";
import path from "node:path";
import { test } from "vitest";
import { normalizeTechIds, renderExport, UnknownTechError, upsertBlock, Vault } from "../src/index.js";

const SEED = path.resolve(import.meta.dirname, "../../../examples/vault");
const BLOCK = "<!-- basics:start -->\n## Stack\n\nbackend: fastapi\n<!-- basics:end -->";

test("upsertBlock creates a new agent file", () => {
  assert.equal(upsertBlock(null, BLOCK), `# Agent instructions\n\n${BLOCK}\n`);
});

test("upsertBlock appends after a blank line", () => {
  assert.equal(upsertBlock("# Notes\n", BLOCK), `# Notes\n\n${BLOCK}\n`);
  assert.equal(upsertBlock("# Notes", BLOCK), `# Notes\n\n${BLOCK}\n`);
});

test("upsertBlock replaces in place and keeps text outside the block", () => {
  const existing = `before\n<!-- basics:start -->\nold\n<!-- basics:end -->\nafter\n`;
  const result = upsertBlock(existing, BLOCK);
  assert.equal(result, `before\n${BLOCK}\nafter\n`);
  assert.ok(result.includes("before\n"));
  assert.ok(result.includes("\nafter\n"));
  assert.ok(!result.includes("old"));
});

test("upsertBlock is idempotent", () => {
  const once = upsertBlock("# Notes\n", BLOCK);
  assert.equal(upsertBlock(once, BLOCK), once);
  assert.equal(upsertBlock(null, BLOCK).match(/basics:start/g)?.length, 1);
});

test("upsertBlock replaces the legacy init-project pointer", () => {
  const legacy = [
    "# Agent instructions",
    "",
    "## Stack",
    "",
    "This project uses: fastapi, react.",
    "Follow the practices in STACK.md and run its checks before finishing a task.",
    "If the basics MCP server is available, use get_stack_context / propose_note to read or extend the stack knowledge.",
    "",
  ].join("\n");
  assert.equal(upsertBlock(legacy, BLOCK), `# Agent instructions\n\n${BLOCK}\n`);

  const keep = `${legacy}Keep this line.\n`;
  const merged = upsertBlock(keep, BLOCK);
  assert.equal(merged, `# Agent instructions\n\n${BLOCK}\nKeep this line.\n`);
});

test("renderExport writes STACK.md plus the requested agent files", () => {
  const vault = Vault.load(SEED);
  const files = renderExport(vault, ["fastapi", "react"], ["agents", "claude", "cursor"], () => null);
  const byPath = new Map(files.map((file) => [file.path, file.content]));

  assert.deepEqual([...byPath.keys()], ["STACK.md", "AGENTS.md", "CLAUDE.md", ".cursor/rules/stack.mdc"]);
  const stack = byPath.get("STACK.md");
  assert.ok(stack?.startsWith("<!-- generated by basics; edit the vault, not this file -->"));
  assert.ok(stack?.includes("FastAPI"));
  assert.ok(stack?.includes("React"));

  for (const agent of ["AGENTS.md", "CLAUDE.md"]) {
    const content = byPath.get(agent);
    assert.ok(content?.startsWith("# Agent instructions\n\n<!-- basics:start -->"));
    assert.ok(content?.includes("backend: fastapi"));
    assert.ok(content?.includes("frontend: react"));
    assert.ok(content?.includes("Follow the practices in STACK.md"));
    assert.ok(content?.includes("get_stack_context / propose_note"));
  }

  const cursor = byPath.get(".cursor/rules/stack.mdc");
  assert.ok(cursor?.startsWith("---\ndescription: Project stack (generated by basics)\nalwaysApply: true\n---\n\n# Stack context"));
});

test("renderExport merges into an existing agent file", () => {
  const vault = Vault.load(SEED);
  const current = "# My rules\n\nKeep this line.\n";
  const files = renderExport(vault, ["fastapi"], ["agents"], (relPath) => (relPath === "AGENTS.md" ? current : null));
  const agents = files.find((file) => file.path === "AGENTS.md")?.content;
  assert.ok(agents?.startsWith("# My rules\n\nKeep this line.\n\n<!-- basics:start -->"));
});

test("renderExport throws listing unknown tech ids", () => {
  const vault = Vault.load(SEED);
  assert.throws(() => renderExport(vault, ["fastapi", "nope"], ["agents"], () => null), /unknown tech ids: nope/);
});

test("renderExport rejects non-tech ids with UnknownTechError", () => {
  const vault = Vault.load(SEED);
  assert.throws(
    () => renderExport(vault, ["fastapi", "backend"], ["agents"], () => null),
    (err: unknown) =>
      err instanceof UnknownTechError && err.message === "unknown tech ids: backend (not a tech note)" && err.ids.length === 1,
  );
});

test("normalizeTechIds resolves references and dedupes", () => {
  const vault = Vault.load(SEED);
  assert.deepEqual(normalizeTechIds(vault, ["[[FastAPI]]", "fastapi", "react", "react"]), ["fastapi", "react"]);
});
